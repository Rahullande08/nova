/**
 * Universal translation retrieval function supporting key lookup,
 * language fallback, parameter interpolation ({{var}}, {var}, $var),
 * and flexible fallback strings.
 */
export function getTranslation(key, lang = 'EN', paramsOrFallback = '', maybeFallback = '') {
  if (!key) return '';
  const selectedLang = (lang || 'EN').toUpperCase();
  const dict = TRANSLATIONS[selectedLang] || TRANSLATIONS.EN;
  let text = dict?.[key] ?? TRANSLATIONS.EN?.[key];

  let params = null;
  let fallback = '';

  if (typeof paramsOrFallback === 'object' && paramsOrFallback !== null) {
    params = paramsOrFallback;
    fallback = typeof maybeFallback === 'string' ? maybeFallback : '';
  } else if (typeof paramsOrFallback === 'string') {
    fallback = paramsOrFallback;
  }

  if (text === undefined || text === null || text === '') {
    text = fallback || key;
  }

  if (params && typeof text === 'string') {
    Object.keys(params).forEach((paramKey) => {
      const val = params[paramKey] !== undefined && params[paramKey] !== null ? params[paramKey] : '';
      text = text
        .replace(new RegExp(`{{\\s*${paramKey}\\s*}}`, 'g'), val)
        .replace(new RegExp(`{\\s*${paramKey}\\s*}`, 'g'), val)
        .replace(new RegExp(`\\$\\s*${paramKey}`, 'g'), val);
    });
  }

  return text;
}
